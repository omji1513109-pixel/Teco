export interface MovementPhase {
  phaseIndex: number;
  name: string;
  timingPercent: number; // 0 to 100
  coachingCue: string;
  voiceCue: string;
  studentJointAngles: {
    label: string;
    studentAngle: string;
    idealAngle: string;
    isFault: boolean;
  }[];
  detectedFaults: string[];
  rightMethodPrescription: string[];
  // 3D joint offsets and rotations for Three.js mannequin
  threeDJoints: {
    student: JointPoses;
    ideal: JointPoses;
  };
}

export interface JointPoses {
  torsoLean: number; // radians / degrees
  pelvisY: number; // height offset
  rightArmPitch: number; // shoulder forward/back
  rightArmRoll: number; // elbow flare outward
  rightElbowBend: number; // elbow flexion
  rightWristFlex: number; // wrist snap
  leftArmPitch: number;
  leftArmRoll: number;
  leftElbowBend: number;
  rightHipPitch: number;
  rightKneeBend: number;
  rightKneeValgus: number; // inward knee cave
  leftHipPitch: number;
  leftKneeBend: number;
  leftKneeValgus: number;
}

